const { start, check, summary, watch } = require('./lib');
const OUT = process.env.SHOTS || '/tmp';
(async () => {
  const { browser, base, stop } = await start(8099);
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 800 }, reducedMotion: 'reduce' });
  const page = await ctx.newPage(); const errors = []; watch(page, errors);
  console.log('Auth');
  await page.goto(base + '/login.html'); await page.waitForSelector('#f');
  await page.fill('[name=email]', 'amina@example.com'); await page.fill('[name=password]', 'wrong'); await page.click('button[type=submit]');
  await page.waitForSelector('.toast.error'); check('wrong password shows an error', /Invalid email or password/.test(await page.textContent('.toast.error')));
  await page.fill('[name=password]', 'Passw0rd!'); await page.click('button[type=submit]');
  await page.waitForSelector('.welcome-back'); check('welcome-back animation shows name', /Welcome back, Amina Test!/.test(await page.textContent('.welcome-back')));
  await page.waitForURL('**/dashboard.html'); await page.waitForSelector('.stat');
  console.log('Dashboard');
  check('8 summary cards', (await page.$$('.grid.cols-4 .stat')).length === 8);
  await page.waitForSelector('#flowChart svg'); check('flow chart drawn', !!(await page.$('#flowChart path.line')));
  check('donut drawn', !!(await page.$('#catChart path.seg')));
  check('insight sentence from data', /Food/.test(await page.textContent('#insights')));
  await page.screenshot({ path: OUT + '/dash-desktop.png', fullPage: true });
  console.log('Add expense');
  await page.click('.hello [data-quick=expense]'); await page.waitForSelector('#txnForm');
  await page.click('#txnForm button[type=submit]'); check('empty form is rejected inline', (await page.$$('.field.invalid')).length >= 2);
  await page.fill('[name=amount]', '12500'); await page.fill('[name=title]', 'Lunch'); await page.selectOption('[name=category_id]', '1');
  await page.click('#txnForm button[type=submit]'); await page.waitForSelector('.saved-check'); check('saved confirmation animation', true);
  await page.waitForSelector('.modal-root', { state: 'detached' });
  console.log('Offline queue + idempotent sync');
  await ctx.setOffline(true);
  await page.click('.hello [data-quick=expense]'); await page.waitForSelector('#txnForm');
  await page.fill('[name=amount]', '3000'); await page.fill('[name=title]', 'Offline bus'); await page.selectOption('[name=category_id]', '2');
  await page.click('#txnForm button[type=submit]'); await page.waitForSelector('.saved-check');
  check('entry queued offline', (await page.evaluate(() => Api.queue.count())) === 1);
  check('offline indicator shown', !!(await page.$('.conn.offline')));
  await page.waitForSelector('.modal-root', { state: 'detached' });
  const before = JSON.parse(await (await fetch(base + '/__mock/state')).text()).txns;
  await ctx.setOffline(false); await page.evaluate(() => window.dispatchEvent(new Event('online')));
  await page.waitForFunction(() => Api.queue.count() === 0, null, { timeout: 5000 });
  const after = JSON.parse(await (await fetch(base + '/__mock/state')).text()).txns;
  check('queue synced once', after === before + 1, before + ' -> ' + after);
  // replay the same uuid: server must not duplicate
  const uuid = await page.evaluate(async () => { const u = Api.uuid(); const b = { title: 'Dup', amount: '10', category_id: 1, account_id: 1, txn_date: '2026-10-19', client_uuid: u }; await Api.post('/api/expenses', b); await Api.post('/api/expenses', b); return u; });
  const dup = JSON.parse(await (await fetch(base + '/__mock/state')).text());
  check('same client_uuid is not saved twice', dup.txns === after + 1 && dup.queueDupes === 1);
  console.log('Expired subscription');
  await fetch(base + '/__mock/expire'); await page.goto(base + '/dashboard.html'); await page.waitForSelector('.banner.danger');
  check('expired banner shown', /expired/i.test(await page.textContent('.banner.danger')));
  check('charts locked for expired users', /subscription/i.test(await page.textContent('#flowChart')));
  await page.goto(base + '/income.html'); await page.waitForSelector('.card.center');
  check('income page gated (not blank)', /needs an active subscription/.test(await page.textContent('#view')));
  await fetch(base + '/__mock/unexpire');
  console.log('Mobile layout');
  const m = await browser.newContext({ viewport: { width: 390, height: 800 }, reducedMotion: 'reduce', isMobile: true, hasTouch: true }); const mp = await m.newPage(); watch(mp, errors);
  await mp.goto(base + '/dashboard.html'); await mp.waitForSelector('.stat');
  check('bottom nav visible on phone', await mp.isVisible('.bottom-nav')); check('FAB visible on phone', await mp.isVisible('#fab'));
  check('no horizontal scroll', await mp.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1));
  await mp.screenshot({ path: OUT + '/dash-mobile.png', fullPage: true });
  await mp.click('#fab'); check('FAB menu opens', await mp.isVisible('#fabMenu'));
  check('no JS errors', errors.length === 0, errors.join(' | '));
  await stop(); summary();
})().catch(e => { console.error(e); process.exit(1); });
